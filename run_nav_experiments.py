#!/usr/bin/env python3
"""Task 2 experiment grid: hazard-aware navigation, normal operation vs cyberattacks vs defenses.

    python run_nav_experiments.py                 # full grid (1,120 episodes; resumable)
    python run_nav_experiments.py --quick         # 2 routes, 4 attacks, none/full, ~5 min smoke test
    python run_nav_experiments.py --policies classical ncm_wm --attacks none odom_spoof --defenses none full

Writes <out>/raw.csv, summary.csv, report.md and figures (default docs/results/nav/).
Policies : classical (pure pursuit) | ncm (NCM planner) | ncm_wm (NCM + world model, proposed)
Attacks  : none | odom_spoof | lidar_phantom | cmd_injection | sensor_replay | dos | coordinated
Defenses : none | crypto | wm | full
Routes   : the 8 held-out TEST_ROUTES (nav/routes.py); learned models never trained on them.
"""
from __future__ import annotations

import os

# One BLAS/OpenMP thread per worker, set before torch is imported anywhere. Forked workers that
# inherit torch's OpenMP pool oversubscribe the CPU (measured: ~6x slower per episode).
for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import argparse  # noqa: E402
import csv  # noqa: E402
import json  # noqa: E402
import multiprocessing as mp  # noqa: E402
import statistics  # noqa: E402
import sys  # noqa: E402
import time  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "ros2_ws", "src", "campussafe_twin"))

from campussafe_twin.nav.attacks import NAV_ATTACKS  # noqa: E402
from campussafe_twin.nav.defense import NAV_DEFENSES  # noqa: E402
from campussafe_twin.nav.routes import TEST_ROUTES  # noqa: E402

POLICIES = ("classical", "ncm", "ncm_wm")
_MODELS = None


def _init():
    global _MODELS
    import torch
    torch.set_num_threads(1)
    try:
        from campussafe_twin.nav.learned import NavModels
        _MODELS = NavModels()
    except Exception as e:  # models missing -> only classical / none / crypto can run
        print(f"(learned models unavailable: {e})")


def _run(job):
    from campussafe_twin.nav.episode import make_nav_policy, run_nav_episode
    route, pol, attack, defense, seed = job
    policy = make_nav_policy(pol, _MODELS)
    monitor = _MODELS.monitor() if defense in ("wm", "full") else None
    r = run_nav_episode(TEST_ROUTES[route], policy, attack, defense, seed, monitor=monitor)
    r["vetoes"] = getattr(policy, "vetoes", 0)
    r["plans"] = getattr(policy, "plans", 0)
    return r


def mean(xs):
    xs = [x for x in xs if x is not None and x == x]
    return statistics.mean(xs) if xs else None


def f(x, d=1, pct=False):
    if x is None:
        return "–"
    return f"{100 * x:.{d}f}%" if pct else f"{x:.{d}f}"


def summarize(rows):
    keys = sorted({(r["policy"], r["attack"], r["defense"]) for r in rows})
    out = []
    for p, a, d in keys:
        g = [r for r in rows if (r["policy"], r["attack"], r["defense"]) == (p, a, d)]
        out.append({
            "policy": p, "attack": a, "defense": d, "runs": len(g),
            "success": mean([r["success"] for r in g]),
            "time_s": mean([r["time_s"] for r in g]),
            "collisions": mean([r["collisions"] for r in g]),
            "runs_with_collision": mean([int(r["collisions"] > 0) for r in g]),
            "exposure_s": mean([r["exposure_s"] for r in g]),
            "min_clearance_m": mean([r["min_clearance_m"] for r in g]),
            "detected": mean([r["detected"] for r in g]) if a != "none" else None,
            "detection_delay_s": mean([r["detection_delay_s"] for r in g]) if a != "none" else None,
            "false_alarm": mean([r["false_alarm"] for r in g]) if a == "none" else None,
            "forged_executed": mean([r["forged_executed"] for r in g]),
            "latency_ms": mean([r["mean_latency_ms"] for r in g]),
            "vetoes_per_run": mean([r["vetoes"] for r in g]),
        })
    base = {(s["policy"], s["defense"]): s for s in out if s["attack"] == "none"}
    for s in out:
        b = base.get((s["policy"], s["defense"])) or base.get((s["policy"], "none"))
        if b and b["success"]:
            tr = min(1.0, (b["time_s"] or 0) / s["time_s"]) if s["time_s"] else 0.0
            s["resilience"] = (s["success"] / b["success"]) * tr
        else:
            s["resilience"] = None
    return out


def report(rows, summ, out_dir, minutes, routes, seeds):
    S = {(s["policy"], s["attack"], s["defense"]): s for s in summ}
    pols = [p for p in POLICIES if any(s["policy"] == p for s in summ)]
    atks = [a for a in NAV_ATTACKS if any(s["attack"] == a for s in summ)]
    defs = [d for d in NAV_DEFENSES if any(s["defense"] == d for s in summ)]
    L = ["# Task 2 results: hazard-aware navigation under cyberattack", "",
         f"Generated by `run_nav_experiments.py` in {minutes:.1f} min: {len(rows)} episodes, "
         f"{len(routes)} held-out routes × {seeds} seed(s). Success = the robot's TRUE position ends within "
         "0.75 m of the goal. Resilience R = (success under attack / normal) × min(1, time normal / time "
         "under attack), same defense.", "",
         "## N1 – Normal operation (no attack, no defense)", "",
         "| Policy | Success | Time (s) | Runs with a collision | Hazard exposure (s) | Min clearance (m) | Latency (ms) |",
         "|---|---|---|---|---|---|---|"]
    for p in pols:
        s = S.get((p, "none", "none"))
        if s:
            L.append(f"| {p} | {f(s['success'], 0, True)} | {f(s['time_s'])} | {f(s['runs_with_collision'], 0, True)} | "
                     f"{f(s['exposure_s'])} | {f(s['min_clearance_m'], 2)} | {f(s['latency_ms'], 2)} |")
    L += ["", "Per route, success / time (s):", "",
          "| Route | " + " | ".join(pols) + " |", "|---|" + "---|" * len(pols)]
    for rn in routes:
        cells = []
        for p in pols:
            g = [r for r in rows if r["route"] == rn and r["policy"] == p and r["attack"] == "none" and r["defense"] == "none"]
            if g:
                cells.append(f"{f(mean([r['success'] for r in g]), 0, True)} / {f(mean([r['time_s'] for r in g]))}")
            else:
                cells.append("–")
        L.append(f"| {rn} | " + " | ".join(cells) + " |")
    L += ["", "## N2 – Attack impact without defense (success / runs with a collision)", "",
          "| Attack | " + " | ".join(pols) + " |", "|---|" + "---|" * len(pols)]
    for a in atks:
        cells = [f"{f(S[(p, a, 'none')]['success'], 0, True)} / {f(S[(p, a, 'none')]['runs_with_collision'], 0, True)}"
                 if (p, a, "none") in S else "–" for p in pols]
        L.append(f"| {a} | " + " | ".join(cells) + " |")
    for p in pols:
        L += ["", f"## N3 – Defenses, policy `{p}`", "",
              "Success / detection rate / resilience R.", "",
              "| Attack | " + " | ".join(defs) + " |", "|---|" + "---|" * len(defs)]
        for a in atks:
            cells = []
            for d in defs:
                s = S.get((p, a, d))
                if not s:
                    cells.append("–")
                    continue
                det = f(s["detected"], 0, True) if a != "none" else f"FA {f(s['false_alarm'], 0, True)}"
                cells.append(f"{f(s['success'], 0, True)} / {det} / R {f(s['resilience'], 2)}")
            L.append(f"| {a} | " + " | ".join(cells) + " |")
        L.append(f"| *runs with a collision* | " + " | ".join(
            f(mean([S[(p, a, d)]['runs_with_collision'] for a in atks if (p, a, d) in S]), 0, True) for d in defs) + " |")
    L += ["", "## Figures", ""] + [f"![{n}]({n})" for n in ("fig_nav_normal.png", "fig_nav_resilience.png")
                                   if os.path.exists(os.path.join(out_dir, n))]
    L += ["", "## Notes", "",
          "- Attacks start 5 s into the run. A detection counts only alarms after that; any alarm in an attack-free "
          "run is a false alarm (FA).",
          "- `wm` cannot reject forged commands (no key); it detects them and engages the motor interlock, so the robot "
          "stops safely but does not finish. `crypto` rejects them.",
          "- The learned models were trained on random routes only; these routes are held out."]
    with open(os.path.join(out_dir, "report.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


def figures(summ, out_dir):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    S = {(s["policy"], s["attack"], s["defense"]): s for s in summ}
    pols = [p for p in POLICIES if (p, "none", "none") in S]
    col = {"classical": "#5A6472", "ncm": "#C9741F", "ncm_wm": "#2F6FB0"}
    fig, axes = plt.subplots(1, 3, figsize=(11, 3.4), dpi=150)
    for ax, (key, label, pct) in zip(axes, (("success", "Success", True), ("time_s", "Time to goal (s)", False),
                                            ("min_clearance_m", "Min wall clearance (m)", False))):
        vals = [S[(p, "none", "none")][key] or 0 for p in pols]
        ax.bar(pols, [v * 100 if pct else v for v in vals], color=[col[p] for p in pols])
        ax.set_title(label, fontsize=10)
        ax.spines[["top", "right"]].set_visible(False)
    fig.suptitle("Task 2, normal operation (8 held-out routes)", fontsize=11)
    fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "fig_nav_normal.png"))
    plt.close(fig)

    atks = [a for a in NAV_ATTACKS if a != "none" and any(k[1] == a for k in S)]
    defs = [d for d in NAV_DEFENSES if any(k[2] == d for k in S)]
    pols_a = [p for p in pols if any(k[0] == p and k[1] != "none" for k in S)]
    fig, axes = plt.subplots(len(pols_a), 1, figsize=(10, 2.6 * len(pols_a) + 0.4), dpi=150, sharex=True,
                             squeeze=False)
    w = 0.8 / len(defs)
    shades = {"none": "#C9C3B6", "crypto": "#8FA7C2", "wm": "#C9741F", "full": "#0F1B2D"}
    for ax, p in zip(axes[:, 0], pols_a):
        for j, d in enumerate(defs):
            ax.bar([i + j * w for i in range(len(atks))],
                   [100 * (S.get((p, a, d), {}).get("success") or 0) for a in atks], w, label=d, color=shades[d])
        base = S.get((p, "none", "none"), {}).get("success")
        if base is not None:
            ax.axhline(100 * base, color="#888", lw=0.8, ls="--")
        ax.set_ylabel("success (%)")
        ax.set_ylim(0, 105)
        ax.set_title(f"policy {p} (dashed: success with no attack)", fontsize=9, loc="left")
        ax.spines[["top", "right"]].set_visible(False)
    axes[-1, 0].legend(frameon=False, fontsize=8, ncol=len(defs), loc="upper right")
    axes[-1, 0].set_xticks([i + w * (len(defs) - 1) / 2 for i in range(len(atks))], atks, fontsize=8)
    fig.suptitle("Task 2 under attack: success by defense", fontsize=11)
    fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "fig_nav_resilience.png"))
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--policies", nargs="+", default=list(POLICIES))
    p.add_argument("--attacks", nargs="+", default=list(NAV_ATTACKS))
    p.add_argument("--defenses", nargs="+", default=list(NAV_DEFENSES))
    p.add_argument("--routes", nargs="+", default=list(TEST_ROUTES))
    p.add_argument("--seeds", type=int, default=3)
    p.add_argument("--learned-seeds", type=int, default=1,
                   help="seeds for the learned policies (greedy plans, so seeds only change sensor noise; "
                        "ncm_wm costs ~19 s per episode on CPU)")
    p.add_argument("--quick", action="store_true")
    p.add_argument("--workers", type=int, default=max(1, min(4, os.cpu_count() or 1)),
                   help="parallel episodes; on small shared VMs 1 can be faster (vCPUs contend)")
    p.add_argument("--out", default=os.path.join(ROOT, "docs", "results", "nav"))
    a = p.parse_args()
    if a.quick:                               # ~5 min on one CPU core
        a.routes, a.seeds = ["corridor_west", "smoke_reroute"], 1
        a.attacks = [x for x in a.attacks if x in ("none", "odom_spoof", "lidar_phantom", "cmd_injection")]
        a.defenses = [x for x in a.defenses if x in ("none", "full")]
    if a.quick:
        a.learned_seeds = 1
    jobs = [(r, pol, atk, d, s) for pol in a.policies for atk in a.attacks for d in a.defenses
            for r in a.routes for s in range(a.seeds if pol == "classical" else min(a.seeds, a.learned_seeds))]
    jobs.sort(key=lambda j: j[1] != "ncm_wm")          # slowest first, for better load balance
    os.makedirs(a.out, exist_ok=True)
    # checkpoint: one JSON line per finished episode, so an interrupted grid resumes where it stopped
    ckpt = os.path.join(a.out, "raw_partial.jsonl")
    rows = []
    if os.path.exists(ckpt):
        with open(ckpt) as fh:
            rows = [json.loads(line) for line in fh if line.strip()]
    done = {(r["route"], r["policy"], r["attack"], r["defense"], r["seed"]) for r in rows}
    rows = [r for r in rows if (r["route"], r["policy"], r["attack"], r["defense"], r["seed"]) in set(jobs)]
    todo = [j for j in jobs if j not in done]
    t0 = time.time()
    print(f"{len(jobs)} episodes ({len(jobs) - len(todo)} from checkpoint) on {a.workers} worker(s) ...",
          flush=True)
    with mp.get_context("spawn").Pool(a.workers, initializer=_init) as pool, open(ckpt, "a") as fh:
        for i, r in enumerate(pool.imap_unordered(_run, todo, chunksize=1), 1):
            rows.append(r)
            fh.write(json.dumps(r) + "\n")
            fh.flush()
            if i % 20 == 0 or i == len(todo):
                print(f"  {i}/{len(todo)}  ({time.time() - t0:.0f}s)", flush=True)
    rows.sort(key=lambda r: (r["policy"], r["attack"], r["defense"], r["route"], r["seed"]))
    with open(os.path.join(a.out, "raw.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    summ = summarize(rows)
    with open(os.path.join(a.out, "summary.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summ[0]))
        w.writeheader()
        w.writerows(summ)
    figures(summ, a.out)
    report(rows, summ, a.out, (time.time() - t0) / 60, a.routes,
           f"{a.seeds} (classical) / {min(a.seeds, a.learned_seeds)} (learned)")
    print(open(os.path.join(a.out, "report.md")).read())
    os.remove(ckpt)
    print(f"Saved {a.out}/raw.csv, summary.csv, report.md, figures")


if __name__ == "__main__":
    main()
